import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

export function localManifest(repositoryRoot: string, revision: string) {
  if (!/^[a-f0-9]{40,64}$/.test(revision)) throw new Error("A full Git commit SHA is required");
  return `# Generated by bun run prepare:local. This manifest is local to this checkout.
id = "elyx"
name = "Elyx"
version = "0.1.0"
schema_version = 1
description = "Syntax highlighting and structure for Elyx design files"
authors = ["Nick Bevers"]

[grammars.elyx]
repository = ${JSON.stringify(pathToFileURL(repositoryRoot).href)}
rev = ${JSON.stringify(revision)}
path = "zed"
`;
}

if (import.meta.main) {
  const extensionRoot = resolve(import.meta.dir, "..");
  const git = (...args: string[]) => execFileSync("git", args, { cwd: extensionRoot, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
  try {
    const repositoryRoot = git("rev-parse", "--show-toplevel");
    const revision = git("rev-parse", "--verify", "HEAD");
    git("cat-file", "-e", `${revision}:zed/src/parser.c`);
    git("diff", "--exit-code", revision, "--", "zed/grammar.js", "zed/src", "zed/languages");
    await Bun.write(resolve(extensionRoot, "extension.toml"), localManifest(repositoryRoot, revision));
    console.log(`Prepared ${resolve(extensionRoot, "extension.toml")} for ${revision}`);
  } catch (error) {
    console.error("Cannot prepare the local Zed extension. Commit the current zed grammar, generated sources and queries first, then rerun bun run prepare:local from zed/.");
    process.exitCode = 1;
  }
}
